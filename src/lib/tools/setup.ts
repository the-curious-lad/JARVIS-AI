import { z } from 'zod';
import { globalToolRegistry } from './registry';
import { executeWebResearch } from '@/lib/workers/researchWorker';
import { documentWorker } from '@/lib/workers/documentWorker';
import { generateEmailDraft } from '@/lib/workers/emailWorker';
import { schedulingWorker } from '@/lib/workers/schedulingWorker';
import { contextEngine } from '@/lib/memory/contextEngine';

let isInitialized = false;

export function initializeToolRegistry() {
  if (isInitialized) return;

  // 1. Research Tool
  globalToolRegistry.register({
    name: 'research_search',
    description: 'Perform web search queries via SerpApi and synthesize findings with source citations',
    inputSchema: z.object({
      query: z.string().min(2, 'Query must be at least 2 characters'),
      contextSummary: z.string().optional(),
    }),
    requiredPermissions: ['web_search'],
    requiresApproval: false,
    category: 'research',
    execute: async (input, ctx) => {
      return await executeWebResearch({
        query: input.query,
        contextSummary: input.contextSummary,
      });
    },
  });

  // 2. Document Creation Tool
  globalToolRegistry.register({
    name: 'document_create',
    description: 'Format research and content into a structured document (Markdown and DOCX exportable)',
    inputSchema: z.object({
      title: z.string().min(1, 'Title is required'),
      type: z.enum(['research_report', 'comparison', 'summary', 'email_draft', 'project_plan']),
      content: z.string().optional(),
      _dependencyResults: z.record(z.any()).optional(),
    }),
    requiredPermissions: ['document_write'],
    requiresApproval: false,
    category: 'document',
    execute: async (input, ctx) => {
      let markdown = input.content || '';
      let sources: any[] = [];

      // If dependent research task exists, extract its findings and citations
      if (input._dependencyResults) {
        for (const depResult of Object.values(input._dependencyResults)) {
          if (depResult && (depResult as any).findings) {
            const res = depResult as any;
            sources = res.sources || [];
            markdown = documentWorker.generateFormattedMarkdown({
              title: input.title,
              summary: 'Comprehensive research and comparative analysis synthesized by Jarvis Copilot.',
              findings: res.findings,
              sources,
            });
            break;
          }
        }
      }

      if (!markdown) {
        markdown = `# ${input.title}\n\nDocument generated by Jarvis.`;
      }

      return await documentWorker.createDocument({
        userId: ctx.userId,
        planId: ctx.planId,
        title: input.title,
        type: input.type,
        markdownContent: markdown,
        sources,
      });
    },
  });

  // 3. Email Draft Tool
  globalToolRegistry.register({
    name: 'email_draft',
    description: 'Generate a professional email draft according to user tone preferences. Does not send without explicit approval.',
    inputSchema: z.object({
      context: z.string().min(2),
      recipient: z.string().optional(),
      tonePreference: z.string().optional(),
    }),
    requiredPermissions: ['email_draft'],
    requiresApproval: false, // Drafting is safe; sending requires approval
    category: 'email',
    execute: async (input, ctx) => {
      return await generateEmailDraft({
        context: input.context,
        recipient: input.recipient,
        tonePreference: input.tonePreference,
      });
    },
  });

  // 4. Scheduling Tool
  globalToolRegistry.register({
    name: 'schedule_manage',
    description: 'Manage tasks, deadlines, conflict analysis, and priority rescheduling',
    inputSchema: z.object({
      action: z.enum(['create', 'list', 'analyze_and_reschedule', 'update', 'delete']),
      title: z.string().optional(),
      priority: z.enum(['low', 'medium', 'high', 'urgent']).optional(),
      estimatedDuration: z.number().optional(),
      deadline: z.string().optional(),
      scheduledStart: z.string().optional(),
      taskId: z.string().optional(),
    }),
    requiredPermissions: ['schedule_write'],
    requiresApproval: false,
    category: 'scheduling',
    execute: async (input, ctx) => {
      if (input.action === 'create' && input.title) {
        return await schedulingWorker.createTask({
          userId: ctx.userId,
          title: input.title,
          priority: input.priority || 'medium',
          estimatedDuration: input.estimatedDuration || 60,
          deadline: input.deadline,
          scheduledStart: input.scheduledStart,
        });
      }

      if (input.action === 'update' && input.taskId) {
        return await schedulingWorker.updateTask(input.taskId, ctx.userId, {
          title: input.title,
          priority: input.priority,
          estimatedDuration: input.estimatedDuration,
          deadline: input.deadline,
          scheduledStart: input.scheduledStart,
        });
      }

      if (input.action === 'delete' && input.taskId) {
        const deleted = await schedulingWorker.deleteTask(input.taskId, ctx.userId);
        return { success: deleted, deletedTaskId: input.taskId };
      }

      const tasks = await schedulingWorker.listTasks(ctx.userId);
      if (input.action === 'analyze_and_reschedule') {
        return schedulingWorker.analyzeAndOptimizeSchedule(tasks);
      }

      return { tasks };
    },
  });

  isInitialized = true;
}

// Auto-initialize on import
initializeToolRegistry();
