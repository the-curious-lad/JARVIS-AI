import { Document, Paragraph, TextRun, HeadingLevel, Packer, Table, TableRow, TableCell, WidthType } from 'docx';
import { GeneratedDocument, DocumentSource } from '@/types';
import { getDb } from '@/lib/db/client';

export class DocumentWorker {
  private collectionName = 'documents';

  private async getCollection() {
    const db = await getDb();
    return db.collection(this.collectionName);
  }

  // Create document in database
  async createDocument(params: {
    userId: string;
    planId?: string;
    title: string;
    type: GeneratedDocument['type'];
    markdownContent: string;
    sources?: DocumentSource[];
  }): Promise<GeneratedDocument> {
    const coll = await this.getCollection();
    const id = `doc_${Date.now()}_${Math.random().toString(36).substring(2, 7)}`;

    const doc: GeneratedDocument = {
      id,
      userId: params.userId,
      planId: params.planId,
      title: params.title,
      type: params.type,
      markdownContent: params.markdownContent,
      sources: params.sources || [],
      createdAt: new Date().toISOString(),
    };

    await coll.insertOne(doc);
    return doc;
  }

  async getDocument(id: string, userId: string): Promise<GeneratedDocument | null> {
    const coll = await this.getCollection();
    return await coll.findOne({ id, userId });
  }

  async listDocuments(userId: string): Promise<GeneratedDocument[]> {
    const coll = await this.getCollection();
    const docs = await coll.find({ userId });
    return docs.sort((a: GeneratedDocument, b: GeneratedDocument) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime());
  }

  // Format research synthesis into structured Markdown
  generateFormattedMarkdown(params: {
    title: string;
    summary: string;
    findings: string;
    sources: DocumentSource[];
    userPreferences?: string;
  }): string {
    const { title, summary, findings, sources } = params;

    const sourceLinksSection = sources.length > 0
      ? `\n\n## References & Verified Sources\n\n` +
        sources
          .map((s, i) => `${i + 1}. [${s.title}](${s.url})${s.snippet ? `\n   > "${s.snippet.trim()}"` : ''}`)
          .join('\n\n')
      : '';

    return `# ${title}\n\n` +
      `*Generated by Jarvis Copilot on ${new Date().toLocaleDateString('en-US', { dateStyle: 'long' })}*\n\n` +
      `## Executive Summary\n\n${summary}\n\n` +
      `## In-Depth Analysis\n\n${findings}` +
      sourceLinksSection;
  }

  // Generate native DOCX binary buffer
  async generateDocxBuffer(doc: GeneratedDocument): Promise<Buffer> {
    const children: any[] = [
      new Paragraph({
        text: doc.title,
        heading: HeadingLevel.TITLE,
      }),
      new Paragraph({
        children: [
          new TextRun({
            text: `Generated by Jarvis Copilot | ${new Date(doc.createdAt).toLocaleDateString()}`,
            italics: true,
            color: '666666',
          }),
        ],
      }),
      new Paragraph({ text: '' }),
    ];

    // Split markdown lines and construct native docx elements
    const lines = doc.markdownContent.split('\n');
    for (const rawLine of lines) {
      const line = rawLine.trim();
      if (!line) {
        children.push(new Paragraph({ text: '' }));
      } else if (line.startsWith('# ')) {
        // Skip title as already added
      } else if (line.startsWith('## ')) {
        children.push(
          new Paragraph({
            text: line.replace('## ', ''),
            heading: HeadingLevel.HEADING_1,
          })
        );
      } else if (line.startsWith('### ')) {
        children.push(
          new Paragraph({
            text: line.replace('### ', ''),
            heading: HeadingLevel.HEADING_2,
          })
        );
      } else if (line.startsWith('- ') || line.startsWith('* ')) {
        children.push(
          new Paragraph({
            text: line.replace(/^[-*]\s+/, ''),
            bullet: { level: 0 },
          })
        );
      } else if (line.startsWith('> ')) {
        children.push(
          new Paragraph({
            children: [
              new TextRun({
                text: line.replace(/^>\s+/, ''),
                italics: true,
                color: '444444',
              }),
            ],
          })
        );
      } else {
        children.push(
          new Paragraph({
            text: line,
          })
        );
      }
    }

    const docxFile = new Document({
      sections: [
        {
          properties: {},
          children,
        },
      ],
    });

    return await Packer.toBuffer(docxFile);
  }
}

export const documentWorker = new DocumentWorker();
